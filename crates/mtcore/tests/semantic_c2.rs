//! L170: semantic ports (crates/mtcore/src/semantic_c2.rs) at the ABI level
//! (EAX, the callee-saved registers, ESP, every memory write but the popped
//! stack scratch, the 4 KiB below the returned ESP; ECX, EDX, the flags and
//! that scratch are not compared):
//!
//! - against the original's recorded vectors (the lifter's lift.json cases
//!   for these functions, extracted to a private file: `L170_VECTORS`,
//!   default E:/ddda-re/notes/native-L170/cases.json; skipped without it
//!   unless DDNATIVE_REQUIRE_VECTORS is set);
//! - on random inputs, against the lifted body of the original (copied
//!   below from crates/ddlift, generated by research/native/lift.py).
use ddnative_base::emit;
use ddnative_base::mem::Mem;
use ddnative_base::x86::{self, Cpu, LiftFn};
use serde_json::Value;
use std::collections::BTreeMap;

/// Guest memory: recorded or written bytes, anything else a fixed function
/// of the address (so any read both bodies make reads the same value).
#[derive(Default, Clone)]
struct Memory {
    bytes: BTreeMap<u32, u8>,
    writes: BTreeMap<u32, u8>,
    /// reads of bytes neither recorded nor written panic (recorded cases)
    strict: bool,
}
impl Mem for Memory {
    fn u8(&self, a: u32) -> u8 {
        match self.bytes.get(&a) {
            Some(&v) => v,
            None if self.strict => panic!("unrecorded read {a:#x}"),
            None => (a.wrapping_mul(0x9E37_79B1) >> 13) as u8,
        }
    }
    fn set_u8(&mut self, a: u32, v: u8) {
        self.bytes.insert(a, v);
        self.writes.insert(a, v);
    }
}
impl Memory {
    fn put(&mut self, a: u32, v: u32) {
        for (k, b) in v.to_le_bytes().into_iter().enumerate() {
            self.bytes.insert(a.wrapping_add(k as u32), b);
        }
    }
}

fn regs(c: &Cpu) -> [u32; 8] {
    [c.eax, c.ecx, c.edx, c.ebx, c.esp, c.ebp, c.esi, c.edi]
}

/// Compare `got` with `want` at the ABI level.
fn abi_equal(what: &str, got: (&Cpu, &Memory), want: (&Cpu, &Memory)) {
    let (g, w) = (regs(got.0), regs(want.0));
    // all but ECX (1) and EDX (2)
    for k in [0, 3, 4, 5, 6, 7] {
        assert_eq!(g[k], w[k], "{what}: register {k} (eax ecx edx ebx esp ebp esi edi)");
    }
    // every write but the popped stack scratch below the returned ESP (the
    // data may lie below the stack: claude-9's L176 finding)
    let esp = w[4];
    let scratch = esp.wrapping_sub(0x1000)..esp;
    let kept = |m: &Memory| m.writes.iter().filter(|(a, _)| !scratch.contains(a)).map(|(&a, &v)| (a, v)).collect::<Vec<_>>();
    assert_eq!(kept(got.1), kept(want.1), "{what}: memory outside the popped stack scratch");
}

fn hex(s: &str) -> Vec<u8> {
    (0..s.len()).step_by(2).map(|k| u8::from_str_radix(&s[k..k + 2], 16).unwrap()).collect()
}

/// The recorded cases of `addr` (lift.json's format), each checked.
fn recorded(addr: u32, port: LiftFn) -> usize {
    let path = std::env::var("L170_VECTORS").unwrap_or_else(|_| "E:/ddda-re/notes/native-L170/cases.json".into());
    recorded_from(&path, addr, port)
}

fn recorded_from(path: &str, addr: u32, port: LiftFn) -> usize {
    let text = match std::fs::read_to_string(path) {
        Ok(t) => t,
        Err(e) if std::env::var_os("DDNATIVE_REQUIRE_VECTORS").is_some() => panic!("{path}: {e}"),
        Err(_) => return 0,
    };
    let cases: Vec<Value> = serde_json::from_str(&text).unwrap();
    let r = |v: &Value, k: &str| v[k].as_u64().unwrap() as u32;
    let mut n = 0;
    for (i, case) in cases.iter().filter(|c| c["addr"].as_u64() == Some(addr as u64)).enumerate() {
        let mut m = Memory { strict: true, ..Default::default() };
        for read in case["reads"].as_array().unwrap() {
            let at = read[0].as_u64().unwrap() as u32;
            for (k, b) in hex(read[1].as_str().unwrap()).into_iter().enumerate() {
                m.bytes.insert(at.wrapping_add(k as u32), b);
            }
        }
        let (i_, o) = (&case["regs_in"], &case["regs_out"]);
        let mut c = Cpu::default();
        [c.eax, c.ecx, c.edx, c.ebx, c.esp, c.ebp, c.esi, c.edi] =
            ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi"].map(|k| r(i_, k));
        let mut want = Cpu::default();
        [want.eax, want.ecx, want.edx, want.ebx, want.esp, want.ebp, want.esi, want.edi] =
            ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi"].map(|k| r(o, k));
        let mut wm = Memory::default();
        for write in case["writes"].as_array().unwrap() {
            let at = write[0].as_u64().unwrap() as u32;
            for (k, b) in hex(write[1].as_str().unwrap()).into_iter().enumerate() {
                wm.set_u8(at.wrapping_add(k as u32), b);
            }
        }
        port(&mut m, &mut c);
        abi_equal(&format!("{addr:#x} recorded case {i}"), (&c, &m), (&want, &wm));
        n += 1;
    }
    n
}

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        (self.0 >> 16) as u32
    }
    fn below(&mut self, n: u32) -> u32 {
        self.next() % n.max(1)
    }
}

/// Run `port` and `original` from the same state; equal at the ABI level.
fn differential(what: &str, port: LiftFn, original: LiftFn, m: &Memory, c: &Cpu) {
    let (mut a, mut ca) = (m.clone(), c.clone());
    let (mut b, mut cb) = (m.clone(), c.clone());
    port(&mut a, &mut ca);
    original(&mut b, &mut cb);
    abi_equal(what, (&ca, &a), (&cb, &b));
}

// verifies 0x01066590 (ABI level)
#[test]
fn find_keyed_entry_matches_the_original() {
    let port = mtcore::semantic_c2::find_keyed_entry;
    let n = recorded(0x0106_6590, port);
    eprintln!("0x01066590: {n} recorded cases");
    let mut rng = Rng(0x0106_6590_9E37_79B9);
    let (this, indices, entries, stack) = (0x0010_0000u32, 0x0020_0000u32, 0x0030_0000u32, 0x0080_0000u32);
    let mut found = 0;
    for case in 0..20_000 {
        let mut m = Memory::default();
        let list = rng.below(2);
        let count = match rng.below(4) {
            0 => rng.below(3),
            _ => rng.below(40),
        };
        m.put(this + 0x88 + 4 * list, count);
        m.put(this + 0x78 + 4 * list, indices);
        m.put(this + 0x30, entries);
        // ids ascending along the index list (the bisection's contract), or,
        // one case in eight, in any order (the original's reads past the
        // ends follow its wrapping arithmetic; Memory answers them)
        let sorted = rng.below(8) != 0;
        let mut id = rng.below(64);
        let mut ids = Vec::new();
        for slot in 0..count {
            let index = rng.below(500);
            id = if sorted { id + rng.below(3) } else { rng.below(4096) };
            ids.push(id);
            m.put(indices + 4 * slot, index);
            m.put(entries + 12 * index, id << 20 | rng.below(1 << 20));
        }
        let key = match (rng.below(3), ids.is_empty()) {
            (0, false) => ids[rng.below(ids.len() as u32) as usize],
            _ => rng.below(4096),
        } | rng.below(0x10_0000) << 12;
        found += ids.contains(&(key & 0xFFF)) as u32;
        m.put(stack, 0xFFFF_0000);
        m.put(stack + 4, list);
        m.put(stack + 8, key);
        let c = Cpu { eax: rng.next(), ecx: this, edx: rng.next(), ebx: rng.next(), esp: stack, ebp: rng.next(), esi: rng.next(), edi: rng.next(), ..Cpu::default() };
        differential(&format!("0x01066590 random case {case}"), port, original_01066590, &m, &c);
    }
    assert!(found > 5_000, "too few cases find their key: {found}");
}

