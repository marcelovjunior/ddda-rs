/// What the stubbed callees saw, in order: target, the eight registers at
/// the call, the two stack words above the return address.
type Calls = Vec<(u32, [u32; 8], [u32; 2])>;

thread_local! {
    static CALLS: std::cell::RefCell<Calls> = const { std::cell::RefCell::new(Vec::new()) };
}
/// The list and the object the update cases use (the stub changes them).
const LIST: u32 = 0x0040_0000;
const THIS: u32 = 0x0050_0000;

/// The callees of 0x01054700, stubbed: logged, a deterministic result,
/// and changes to what the loop reads again (list bytes ahead, element
/// flags, the element bank), then their own `ret`.
fn stub(m: &mut dyn Mem, c: &mut Cpu, target: u32) {
    let args = [m.u32(c.esp.wrapping_add(4)), m.u32(c.esp.wrapping_add(8))];
    let n = CALLS.with(|l| {
        let mut l = l.borrow_mut();
        l.push((target, regs(c), args));
        l.len() as u32
    });
    let h = (target ^ args[0].rotate_left(7) ^ n.wrapping_mul(0x9E37_79B1)).wrapping_mul(0x85EB_CA6B);
    match h % 8 {
        0 => {
            let bank = m.u32(THIS + 0x364);
            m.set_u32(THIS + 0x364, bank.wrapping_add(0xA0));
        }
        1 => m.set_u8(LIST + (h >> 8) % 16, (h >> 16) as u8 % 8),
        2 => {
            let at = m.u32(THIS + 0x364).wrapping_add((h >> 8) % 8 * 0xA0 + 0x90);
            let v = m.u8(at) ^ 0x20;
            m.set_u8(at, v);
        }
        3 => {
            let at = m.u32(THIS + 0x364).wrapping_add((h >> 8) % 8 * 0xA0 + 0x96);
            let v = m.u8(at) ^ 1;
            m.set_u8(at, v);
        }
        _ => {}
    }
    // caller-saved registers clobbered, callee-saved kept
    c.eax = h;
    c.ecx = h.rotate_left(3);
    c.edx = h.rotate_left(11);
    let popped = match target {
        0x0105_4690 => 0,
        0x0104_EF10 | 0x0105_1B60 | 0x0105_33A0 | 0x0105_2330 => 1,
        _ => 2,
    };
    c.esp = c.esp.wrapping_add(4 + 4 * popped);
}

/// Run `body` with the stubbed callees: its result and the calls it made.
fn with_stub(body: LiftFn, m: &mut Memory, c: &mut Cpu) -> Calls {
    CALLS.with(|l| l.borrow_mut().clear());
    ddnative_base::x86::set_ext_calls(Some(Box::new(stub)));
    body(m, c);
    ddnative_base::x86::set_ext_calls(None);
    CALLS.with(|l| std::mem::take(&mut *l.borrow_mut()))
}

