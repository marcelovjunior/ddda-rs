/// The recorded cases of `addr` run with the stub (cases without calls
/// compare as recorded; a case that calls out is skipped: its callees'
/// effects are in the recording).
fn recorded_with_stub(addr: u32, port: LiftFn) -> usize {
    let mut n = 0;
    let path = std::env::var("L170_VECTORS").unwrap_or_else(|_| "E:/ddda-re/notes/native-L170/cases.json".into());
    let Ok(text) = std::fs::read_to_string(&path) else { return 0 };
    let cases: Vec<Value> = serde_json::from_str(&text).unwrap();
    for case in cases.iter().filter(|c| c["addr"].as_u64() == Some(addr as u64)) {
        let one = serde_json::to_string(&vec![case]).unwrap();
        let file = std::env::temp_dir().join(format!("l170_case_{addr:x}_{n}.json"));
        std::fs::write(&file, one).unwrap();
        // a case whose original calls out reads the stub's results: skip it
        CALLS.with(|l| l.borrow_mut().clear());
        ddnative_base::x86::set_ext_calls(Some(Box::new(stub)));
        let r = std::panic::catch_unwind(|| recorded_from(&file.to_string_lossy(), addr, port));
        ddnative_base::x86::set_ext_calls(None);
        let called = CALLS.with(|l| !l.borrow().is_empty());
        let _ = std::fs::remove_file(&file);
        match r {
            Ok(k) => n += k,
            Err(e) if called => drop(e),
            Err(e) => std::panic::resume_unwind(e),
        }
    }
    n
}
