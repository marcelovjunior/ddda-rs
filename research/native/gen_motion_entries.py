"""Generates crates/ddnative/src/generated/motion_entries.rs and
crates/ddnative/tests/motion_entries.rs from patterns/motion_entry.json
(the recognizer's per-function specs). Each entry carries its own
'Translated from' line; the test declares every address it verifies."""
import json, os
N = "E:/ddda-re/notes/native"
R = os.path.join(os.path.dirname(__file__), "..", "..")
specs = json.load(open(f"{N}/patterns/motion_entry.json"))
specs.sort(key=lambda s: s["addr"])
arg = lambda a: f"Const(0x{a[1]:08X})" if a[0] == "const" else f"Field(0x{a[1]:X})"
lines = ["//! Generated by research/native/gen_motion_entries.py: do not edit.",
         "//! Each entry is one translated function (see `action::motion_entry`).", "",
         "use crate::action::MotionArg::{Const, Field};", "use crate::action::MotionEntry;", "",
         "pub const MOTION_ENTRIES: &[MotionEntry] = &["]
for s in specs:
    lines.append(f"    // Translated from 0x{s['addr']:08X} (DDDA.exe 2017-12-13 Steam), {s['name']}.")
    lines.append(f"    MotionEntry {{ addr: 0x{s['addr']:08X}, base: 0x{s['base']:08X}, args: [{', '.join(arg(a) for a in s['args'])}] }},")
lines += ["];", ""]
open(os.path.join(R, "crates/ddnative/src/generated/motion_entries.rs"), "w").write("\n".join(lines))
addrs = " ".join(f"0x{s['addr']:08X}" for s in specs)
test = f'''//! Generated by research/native/gen_motion_entries.py: do not edit.
use ddnative::action::{{motion_entry, MotionOwner}};
use ddnative::generated::motion_entries::MOTION_ENTRIES;
use serde_json::Value;

fn vectors(name: &str) -> Option<Vec<Value>> {{
    let path = format!("E:/ddda-re/notes/native/vectors/{{name}}.json");
    let text = match std::fs::read_to_string(&path) {{
        Ok(t) => t,
        Err(e) if std::env::var_os("DDNATIVE_REQUIRE_VECTORS").is_some() => panic!("{{path}}: {{e}}"),
        Err(_) => return None,
    }};
    serde_json::from_str::<Value>(&text).ok()?.as_array().cloned()
}}

struct Capture(Option<[u32; 6]>);
impl MotionOwner for Capture {{
    fn request_motion(&mut self, args: [u32; 6]) {{ self.0 = Some(args); }}
}}

// verifies {addrs}
#[test]
fn every_motion_entry_matches_the_original() {{
    let Some(cases) = vectors("motion_entry") else {{ return }};
    let mut seen = std::collections::HashSet::new();
    for c in &cases {{
        let addr = c["addr"].as_u64().unwrap() as u32;
        let e = MOTION_ENTRIES.iter().find(|e| e.addr == addr).expect("entry in the table");
        let mut base_ran = false;
        let mut owner = Capture(None);
        motion_entry(e, || base_ran = true, |off| c["fields"][off.to_string()].as_u64().unwrap() as u32, &mut owner);
        let want: Vec<u32> = c["captured"].as_array().unwrap().iter().map(|v| v.as_u64().unwrap() as u32).collect();
        assert!(base_ran);
        assert_eq!(owner.0.unwrap().to_vec(), want, "{{:#010x}}", addr);
        assert_eq!(c["this"], c["owner"], "the request goes to the owner the base kept");
        seen.insert(addr);
    }}
    assert_eq!(seen.len(), MOTION_ENTRIES.len(), "every table entry has vectors");
}}
'''
open(os.path.join(R, "crates/ddnative/tests/motion_entries.rs"), "w").write(test)
print(len(specs), "entries generated")
