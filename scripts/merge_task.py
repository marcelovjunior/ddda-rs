#!/usr/bin/env python3
"""Head's merge of a reviewed task branch into main, with checks.

    python scripts/merge_task.py <brief-id> [crate ...]

1. `git merge --no-ff task/<id>`.
2. Additive clashes in the shared hookup files are resolved by keeping both
   sides (crates/ddtool/src/main.rs, crates/ddtool/Cargo.toml); Cargo.lock
   is taken from main and regenerated by cargo.
3. Refuses to commit if any conflict marker remains anywhere, or if
   `cargo test -p <crate>` (the given crates, plus ddtool) fails. On
   failure the merge is aborted and main is left as it was.
4. Commits as the maintainer, with no AI trailer, and marks the brief
   merged in docs/tasks/README.md.
"""
import datetime
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IDENT = ['-c', 'user.name=janne', '-c', 'user.email=marcelovjunior55@gmail.com']
ADDITIVE = ['crates/ddtool/src/main.rs', 'crates/ddtool/Cargo.toml']
BLOCK = re.compile(r'<<<<<<< [^\n]*\n(.*?)=======\r?\n(.*?)>>>>>>> [^\n]*\n', re.S)


def git(*args, check=True):
    r = subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True)
    if check and r.returncode:
        raise SystemExit(f'git {" ".join(args)} failed:\n{r.stdout}{r.stderr}')
    return r


def abort(msg):
    git('merge', '--abort', check=False)
    raise SystemExit(f'ABORTED: {msg}\nmain is unchanged.')


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    bid, crates = sys.argv[1], sys.argv[2:]
    if git('status', '--porcelain', '--untracked-files=no').stdout.strip():
        raise SystemExit('main has uncommitted changes; commit or stash them first')
    title = f'Merge task/{bid}'
    r = git(*IDENT, 'merge', '--no-ff', '--no-commit', f'task/{bid}', check=False)
    conflicted = git('diff', '--name-only', '--diff-filter=U').stdout.split()
    for path in conflicted:
        full = os.path.join(ROOT, path)
        if path in ADDITIVE:
            text = open(full, encoding='utf-8', newline='').read()
            text, n = BLOCK.subn(lambda m: m.group(1) + m.group(2), text)
            open(full, 'w', encoding='utf-8', newline='').write(text)
            print(f'{path}: kept both sides of {n} block(s)')
            git('add', path)
        elif path == 'Cargo.lock':
            git('checkout', '--ours', 'Cargo.lock')
            git('add', 'Cargo.lock')
        else:
            abort(f'real conflict in {path}; resolve by hand')
    if r.returncode and not conflicted:
        abort(r.stdout + r.stderr)
    markers = git('grep', '-lE', '^(<<<<<<<|>>>>>>>) ', '--', 'crates', 'docs', 'scripts', 'research', 'Cargo.lock',
                  check=False).stdout.split()
    if markers:
        abort(f'conflict markers remain in {markers}')
    test = ['cargo', 'test', '-q']
    for c in sorted(set(crates) | {'ddtool'}):
        test += ['-p', c]
    t = subprocess.run(test, cwd=ROOT, capture_output=True, text=True)
    if t.returncode:
        print(t.stdout[-3000:], t.stderr[-3000:])
        abort('tests failed')
    git('add', 'Cargo.lock')
    readme = os.path.join(ROOT, 'docs', 'tasks', 'README.md')
    s = open(readme, encoding='utf-8').read()
    today = datetime.date.today().isoformat()
    s2 = re.sub(rf'(\| \[{re.escape(bid)}\]\({re.escape(bid)}\.md\) \|[^\n]*\| )([^|\n]*)\| ([^|\n]*) \|\n',
                lambda m: f'{m.group(1)}{m.group(2)}| merged {today} |\n', s)
    if s2 != s:
        open(readme, 'w', encoding='utf-8').write(s2)
        git('add', 'docs/tasks/README.md')
    git(*IDENT, 'commit', '-q', '-m', title)
    print(git('log', '--oneline', '-1').stdout.strip())
    passed = sum(int(n) for n in re.findall(r'(\d+) passed', t.stdout))
    print(f'tests: {passed} passed')


if __name__ == '__main__':
    main()
